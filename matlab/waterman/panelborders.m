function [xb,yb,varargout] = panelborders(p)
% PANELBORDERS - computes octahedral coordinates for map borders
%
%   [xb,yb,varargout] = panelborders(p) computes borders for octahedral
%   maps using the input parameters p, which are passed by the calling
%   function.  Required parameters include the projection, style and inset
%   flag.
%
% see also: OctahedralProjection octaborder

blon = [-179.999999  -89.999999  0.000001  90.000001;
    -179.999999  -90  0.00000  90.00000;
    -179.999999  -90  0.00000  90.00000;
    -179.999999  -89.999999  0.000001  90.00000;
    -161.3603887  -71.36038869  18.63961131  108.6396113;
    -179.999999  -89.999999  0.000001  90.000001;
    -179.999999  -89.999999  0.000001  90.000001;
    -179.999999  -89.999999  0.000001  90.000001;
    -179.999999  -89.999999  0.000001  90.000001;
    -90.000001  -0.000001  89.999999  179.999999;
    -90.000001  -0.000001  89.999999  179.999999;
    -90.000001  -0.000001  89.999999  179.999999;
    -90.000001  -0.000001  89.999999  179.999999;
    -108.6396113  -18.63961131  71.36038869  161.3603887;
    -90.000001  -0.000001  89.999999  179.999999;
    -90.00000  0.00000  90  179.999999;
    -90.00000  0.00000  90  179.999999;
    -90.000001  -0.000001  89.999999  179.999999];

blat = [89.999999  89.999999  89.999999  89.999999;
    71.38865281  71.38865281  71.38865281  71.38865281;
    18.7478136  18.7478136  18.7478136  18.7478136;
    0.000001  0.000001  0.000001  0.000001;
    0  0  0  0;
    -0.000001  -0.000001  -0.000001  -0.000001;
    -18.7478136  -18.7478136  -18.7478136  -18.7478136;
    -71.38865281  -71.38865281  -71.38865281  -71.38865281;
    -89.999999  -89.999999  -89.999999  -89.999999;
    -89.999999  -89.999999  -89.999999  -89.999999;
    -71.38865281  -71.38865281  -71.38865281  -71.38865281;
    -18.7478136  -18.7478136  -18.7478136  -18.7478136;
    -0.000001  -0.000001  -0.000001  -0.000001;
    0  0  0  0;
    0.000001  0.000001  0.000001  0.000001;
    18.7478136  18.7478136  18.7478136  18.7478136;
    71.38865281  71.38865281  71.38865281  71.38865281;
    89.999999  89.999999  89.999999  89.999999];

[xb,yb] = OctahedralProjection(blat,blon, ...
    'Projection',p.Results.Projection, ...
    'Style',p.Results.Style, ...
    'MaxLat',p.Results.MaxLat);

maxlat = p.Results.MaxLat;

if p.Results.Inset
    blon2 = [linspace(-179.9999,-90.0001,90) -90.0001 -90.0001 -89.9999 -89.9999 ...
            linspace(-89.9999,-0.0001,90) -0.0001 -0.0001 0.0001 0.0001 ...
            linspace(0.0001,89.9999,90) 89.9999 89.9999 90.0001 90.0001 ...
            linspace(90.0001,179.9999,90) 179.9999 179.9999 -179.9999 -179.9999];
    blat2 = [repmat(maxlat,1,90) maxlat -71.38865281 -71.38865 maxlat ...
        repmat(maxlat,1,90) maxlat -71.38865281 -71.38865281 maxlat ...
        repmat(maxlat,1,90) maxlat -71.38865281 -71.38865281 maxlat ...
        repmat(maxlat,1,90)  maxlat -71.38865281 -71.38865281 maxlat];

    [~,~,xbi,ybi] = OctahedralProjection(blat2,blon2, ...
        'Projection',p.Results.Projection, ...
        'Style',p.Results.Style,'Inset',true, ...
        'MaxLat',p.Results.MaxLat);

    varargout{1} = xbi;
    varargout{2} = ybi;
end

return